# api/schemas.py
from pydantic import BaseModel, Field
from typing import List, Optional

class ChatRequest(BaseModel):
    """
    Validates the incoming JSON payload from the client (e.g., Streamlit).
    """
    question: str = Field(
        ..., 
        description="The natural language financial question to ask the ReAct agent.",
        examples=["What is the difference between BlackRock's revenue and Goldman Sachs' revenue in 2025?"]
    )

class ChatResponse(BaseModel):
    """
    Guarantees the structural output format sent back to the client.
    """
    answer: str = Field(..., description="The final text answer generated by the ReAct agent.")
    status: str = Field("success", description="The execution status string ('success' or 'error').")
    errors: Optional[str] = Field(None, description="Detailed error messages if execution fails.")